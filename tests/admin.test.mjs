/*
 * The admin editor's one promise: a save that would leave content/ invalid is
 * rejected and the previous file put back. It used to break that promise on
 * Windows for every file in a subfolder (announcements, generated/*), because
 * the error filter compared a backslash path against forward-slash messages.
 *
 * Runs against a throwaway copy of content/ -- never the real one.
 *
 * Run with: node --test tests/admin.test.mjs
 */
import test from "node:test";
import assert from "node:assert/strict";
import path from "node:path";
import { promises as fs } from "node:fs";
import { saveContentFile } from "../admin/server.mjs";
import { makeFixture, cleanup } from "./helpers/build-fixture.mjs";

const ANNOUNCEMENTS = path.join("announcements", "announcements.json");

test("an invalid save to a nested file is rolled back", async (t) => {
  const dir = await makeFixture();
  t.after(() => cleanup(dir));
  const contentDir = path.join(dir, "content");
  const file = path.join(contentDir, ANNOUNCEMENTS);
  const before = await fs.readFile(file, "utf8");

  const doc = JSON.parse(before);
  doc.announcements.push({ id: "no-title" }); // title is required
  const { status, body } = await saveContentFile({ contentDir, name: "announcements", raw: JSON.stringify(doc) });

  assert.equal(status, 400);
  assert.ok(body.details.some((d) => /no-title/.test(d)), JSON.stringify(body));
  assert.equal(await fs.readFile(file, "utf8"), before, "the previous file must be restored byte for byte");
});

test("a valid save to a nested file is kept, extra fields and all", async (t) => {
  const dir = await makeFixture();
  t.after(() => cleanup(dir));
  const contentDir = path.join(dir, "content");

  const doc = JSON.parse(await fs.readFile(path.join(contentDir, ANNOUNCEMENTS), "utf8"));
  doc.announcements.push({ id: "thanks", title: "Thank you", body: "", showRegistration: false });
  const { status } = await saveContentFile({ contentDir, name: "announcements", raw: JSON.stringify(doc) });

  assert.equal(status, 200);
  const saved = JSON.parse(await fs.readFile(path.join(contentDir, ANNOUNCEMENTS), "utf8"));
  assert.equal(saved.announcements.at(-1).showRegistration, false);
});

test("generated files cannot be written through the admin", async (t) => {
  const dir = await makeFixture();
  t.after(() => cleanup(dir));
  const contentDir = path.join(dir, "content");
  const file = path.join(contentDir, "generated", "events.json");
  const before = await fs.readFile(file, "utf8");

  for (const name of ["events", "gallery"]) {
    const { status, body } = await saveContentFile({ contentDir, name, raw: "{}" });
    assert.equal(status, 403, name);
    assert.match(body.error, /generated by the sync/);
  }
  assert.equal(await fs.readFile(file, "utf8"), before);
});

test("an unknown file name is refused", async () => {
  const { status } = await saveContentFile({ contentDir: "unused", name: "../../package", raw: "{}" });
  assert.equal(status, 400);
});
